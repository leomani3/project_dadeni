    public static class CardTable
    {
        public const string FilePath = "Content/Cards.txt";

        private const string NullToken = "-";
        private const string NoneToken = "(none)";

        private static readonly CultureInfo Invariant = CultureInfo.InvariantCulture;

        private sealed class Variant
        {
            public int cost;
            public ActionResourceConfig costResource;
            public bool exhausts;
            public bool requiresLineOfSight;
            public ZoneDefinition targetZone;
            public ZoneDefinition effectZone;
            public List<CardAction> actions = new List<CardAction>();
        }

        private sealed class Entry
        {
            public string id;
            public string title;
            public CardType type;
            public CastStyle castStyle;
            public Variant baseVariant = new Variant();
            public Variant upgradedVariant = new Variant();
        }

        [MenuItem("Deckbuilder/Cards/Export Table")]
        public static void ExportMenu()
        {
            Debug.Log(Export());
        }

        [MenuItem("Deckbuilder/Cards/Import Table (dry run)")]
        public static void ImportDryRunMenu()
        {
            Debug.Log(Import(true));
        }

        [MenuItem("Deckbuilder/Cards/Import Table")]
        public static void ImportMenu()
        {
            Debug.Log(Import(false));
        }

        public static string Export()
        {
            List<CardConfig> _cards = LoadAllCards();

            StringBuilder _builder = new StringBuilder();
            _builder.Append("# Generated by Deckbuilder/Cards/Export Table. ").Append(_cards.Count).AppendLine(" cards.");
            _builder.AppendLine("# Rules only: the illustration stays authored on the asset. cast names an animation style each character resolves.");
            _builder.AppendLine("# Edit this file, then run Deckbuilder/Cards/Import Table to write it back.");

            foreach (CardConfig _card in _cards)
            {
                _builder.AppendLine();
                _builder.Append(Render(FromAsset(_card)));
            }

            string _text = _builder.ToString().Replace("\r\n", "\n");
            File.WriteAllText(AbsolutePath(), _text);
            AssetDatabase.Refresh();

            return $"Exported {_cards.Count} cards to {FilePath}";
        }

        public static string Import(bool _dryRun)
        {
            string _absolutePath = AbsolutePath();

            if (!File.Exists(_absolutePath))
                return $"{FilePath} does not exist. Run Deckbuilder/Cards/Export Table first.";

            List<string> _errors = new List<string>();
            List<Entry> _entries = ParseFile(File.ReadAllText(_absolutePath), _errors);

            Dictionary<string, CardConfig> _cardsById = new Dictionary<string, CardConfig>();

            foreach (CardConfig _card in LoadAllCards())
            {
                string _id = IdOf(_card);

                if (_cardsById.ContainsKey(_id))
                    _errors.Add($"Two card assets share the id '{_id}': {_cardsById[_id].name} and {_card.name}.");
                else
                    _cardsById[_id] = _card;
            }

            List<string> _changed = new List<string>();
            List<KeyValuePair<CardConfig, Entry>> _toWrite = new List<KeyValuePair<CardConfig, Entry>>();
            HashSet<string> _seen = new HashSet<string>();

            foreach (Entry _entry in _entries)
            {
                if (!_seen.Add(_entry.id))
                    _errors.Add($"Card '{_entry.id}' appears more than once in the file.");

                if (!_cardsById.TryGetValue(_entry.id, out CardConfig _card))
                {
                    _errors.Add($"No CardConfig asset has the id '{_entry.id}'. Create the asset in Unity first; import never creates assets.");
                    continue;
                }

                if (Render(_entry) == Render(FromAsset(_card)))
                    continue;

                _changed.Add(_entry.id);
                _toWrite.Add(new KeyValuePair<CardConfig, Entry>(_card, _entry));
            }

            foreach (string _id in _cardsById.Keys)
            {
                if (!_seen.Contains(_id))
                    _errors.Add($"Card '{_id}' exists as an asset but is missing from the file; it was left untouched.");
            }

            if (_errors.Count > 0)
                return $"Import aborted with {_errors.Count} problem(s); nothing was written.\n  " + string.Join("\n  ", _errors);

            if (_changed.Count == 0)
                return $"Import: all {_entries.Count} cards already match {FilePath}. Nothing to write.";

            if (_dryRun)
                return $"Dry run: {_changed.Count} of {_entries.Count} cards would change.\n  " + string.Join("\n  ", _changed);

            foreach (KeyValuePair<CardConfig, Entry> _pair in _toWrite)
            {
                ApplyTo(_pair.Key, _pair.Value);
                EditorUtility.SetDirty(_pair.Key);
            }

            AssetDatabase.SaveAssets();

            return $"Imported {_changed.Count} changed card(s) from {FilePath}.\n  " + string.Join("\n  ", _changed);
        }

        private static Entry FromAsset(CardConfig _card)
        {
            return new Entry
            {
                id = IdOf(_card),
                title = _card.Title,
                type = _card.Type,
                castStyle = _card.CastStyle,
                baseVariant = VariantFromAsset(_card, false),
                upgradedVariant = VariantFromAsset(_card, true)
            };
        }

        private static Variant VariantFromAsset(CardConfig _card, bool _upgraded)
        {
            Variant _variant = new Variant
            {
                cost = _card.GetCost(_upgraded),
                costResource = _card.GetCostResource(_upgraded),
                exhausts = _card.GetExhausts(_upgraded),
                requiresLineOfSight = _card.GetRequiresLineOfSight(_upgraded),
                targetZone = _card.GetTargetZone(_upgraded),
                effectZone = _card.GetEffectZone(_upgraded)
            };

            IReadOnlyList<CardAction> _actions = _card.GetActions(_upgraded);

            if (_actions != null)
                _variant.actions.AddRange(_actions);

            return _variant;
        }

        private static void ApplyTo(CardConfig _card, Entry _entry)
        {
            SetField(_card, "m_title", _entry.title);
            SetField(_card, "m_type", _entry.type);
            SetField(_card, "m_castStyle", _entry.castStyle);

            ApplyVariant(_card, _entry.baseVariant, false);
            ApplyVariant(_card, _entry.upgradedVariant, true);
        }

        private static void ApplyVariant(CardConfig _card, Variant _variant, bool _upgraded)
        {
            string _suffix = _upgraded ? "Upgraded" : string.Empty;

            SetField(_card, "m_cost" + _suffix, _variant.cost);
            SetField(_card, "m_costResource" + _suffix, _variant.costResource);
            SetField(_card, "m_exhausts" + _suffix, _variant.exhausts);
            SetField(_card, "m_requiresLineOfSight" + _suffix, _variant.requiresLineOfSight);
            SetField(_card, "m_targetZone" + _suffix, _variant.targetZone);
            SetField(_card, "m_effectZone" + _suffix, _variant.effectZone);
            SetField(_card, "m_actions" + _suffix, _variant.actions);
        }

        private static void SetField(object _target, string _name, object _value)
        {
            foreach (FieldInfo _field in SerializedFieldsOf(_target.GetType()))
            {
                if (_field.Name != _name)
                    continue;

                _field.SetValue(_target, _value);
                return;
            }

            throw new InvalidOperationException($"{_target.GetType().Name} has no serialized field named '{_name}'.");
        }

        private static string Render(Entry _entry)
        {
            StringBuilder _builder = new StringBuilder();

            _builder.Append("card ").AppendLine(_entry.id);
            _builder.Append("  title  ").AppendLine(_entry.title ?? string.Empty);
            _builder.Append("  type   ").AppendLine(_entry.type.ToString());
            _builder.Append("  cast   ").AppendLine(_entry.castStyle.ToString());

            RenderVariant(_builder, "base", _entry.baseVariant);
            RenderVariant(_builder, "upgraded", _entry.upgradedVariant);

            return _builder.ToString();
        }

        private static void RenderVariant(StringBuilder _builder, string _label, Variant _variant)
        {
            _builder.Append("  ").AppendLine(_label);
            _builder.Append("    cost     ").Append(_variant.cost.ToString(Invariant)).Append(' ').AppendLine(FormatValue(_variant.costResource));
            _builder.Append("    exhausts ").AppendLine(_variant.exhausts ? "yes" : "no");
            _builder.Append("    los      ").AppendLine(_variant.requiresLineOfSight ? "yes" : "no");
            _builder.Append("    target   ").AppendLine(RenderObject(_variant.targetZone));
            _builder.Append("    effect   ").AppendLine(RenderObject(_variant.effectZone));

            if (_variant.actions == null || _variant.actions.Count == 0)
            {
                _builder.Append("    action   ").AppendLine(NoneToken);
                return;
            }

            foreach (CardAction _action in _variant.actions)
                _builder.Append("    action   ").AppendLine(RenderObject(_action));
        }

        private static string RenderObject(object _target)
        {
            if (_target == null)
                return NoneToken;

            StringBuilder _builder = new StringBuilder(_target.GetType().Name);

            foreach (FieldInfo _field in SerializedFieldsOf(_target.GetType()))
                _builder.Append(' ').Append(TrimFieldName(_field.Name)).Append('=').Append(FormatValue(_field.GetValue(_target)));

            return _builder.ToString();
        }

        private static List<Entry> ParseFile(string _text, List<string> _errors)
        {
            List<Entry> _entries = new List<Entry>();

            Entry _entry = null;
            Variant _variant = null;
            string _variantLabel = null;

            string[] _lines = _text.Replace("\r\n", "\n").Replace('\r', '\n').Split('\n');

            for (int _lineNumber = 1; _lineNumber <= _lines.Length; _lineNumber++)
            {
                string _raw = _lines[_lineNumber - 1];
                string _line = _raw.Trim();

                if (_line.Length == 0 || _line.StartsWith("#"))
                    continue;

                string _where = $"line {_lineNumber}";
                SplitFirstWord(_line, out string _keyword, out string _rest);

                switch (_keyword)
                {
                    case "card":
                        if (_rest.Length == 0)
                        {
                            _errors.Add($"{_where}: 'card' needs an id.");
                            continue;
                        }

                        _entry = new Entry { id = _rest, title = _rest, type = default };
                        _entries.Add(_entry);
                        _variant = null;
                        continue;

                    case "base":
                    case "upgraded":
                        if (_entry == null)
                        {
                            _errors.Add($"{_where}: '{_keyword}' appears before any 'card' line.");
                            continue;
                        }

                        _variantLabel = _keyword;
                        _variant = _keyword == "base" ? _entry.baseVariant : _entry.upgradedVariant;
                        continue;
                }

                if (_entry == null)
                {
                    _errors.Add($"{_where}: '{_keyword}' appears before any 'card' line.");
                    continue;
                }

                if (_keyword == "title")
                {
                    _entry.title = Unquote(_rest);
                    continue;
                }

                if (_keyword == "type")
                {
                    if (ParseValue(_rest, typeof(CardType), _where, _errors) is CardType _cardType)
                        _entry.type = _cardType;

                    continue;
                }

                if (_keyword == "cast")
                {
                    if (ParseValue(_rest, typeof(CastStyle), _where, _errors) is CastStyle _castStyle)
                        _entry.castStyle = _castStyle;

                    continue;
                }

                if (_variant == null)
                {
                    _errors.Add($"{_where}: '{_keyword}' appears outside a 'base' or 'upgraded' block.");
                    continue;
                }

                string _context = $"{_where} ({_entry.id}/{_variantLabel})";

                switch (_keyword)
                {
                    case "cost":
                        SplitFirstWord(_rest, out string _costAmount, out string _costResource);

                        if (ParseValue(_costAmount, typeof(int), _context, _errors) is int _cost)
                            _variant.cost = _cost;

                        if (_costResource.Length == 0)
                            _errors.Add($"{_context}: 'cost' needs an amount and an action resource, e.g. 'cost 1 ActionPoints'.");
                        else
                            _variant.costResource = (ActionResourceConfig)ParseValue(_costResource, typeof(ActionResourceConfig), _context, _errors);
                        break;

                    case "exhausts":
                        if (ParseValue(_rest, typeof(bool), _context, _errors) is bool _exhausts)
                            _variant.exhausts = _exhausts;
                        break;

                    case "los":
                        if (ParseValue(_rest, typeof(bool), _context, _errors) is bool _los)
                            _variant.requiresLineOfSight = _los;
                        break;

                    case "target":
                        _variant.targetZone = (ZoneDefinition)BuildObject(_rest, typeof(ZoneDefinition), _context, _errors);
                        break;

                    case "effect":
                        _variant.effectZone = (ZoneDefinition)BuildObject(_rest, typeof(ZoneDefinition), _context, _errors);
                        break;

                    case "action":
                        CardAction _action = (CardAction)BuildObject(_rest, typeof(CardAction), _context, _errors);

                        if (_action != null)
                            _variant.actions.Add(_action);
                        break;

                    default:
                        _errors.Add($"{_context}: unknown key '{_keyword}'.");
                        break;
                }
            }

            return _entries;
        }

        private static object BuildObject(string _text, Type _expectedBase, string _context, List<string> _errors)
        {
            if (_text == NoneToken || _text == NullToken || _text.Length == 0)
                return null;

            List<string> _tokens = Tokenize(_text);

            if (_tokens.Count == 0)
            {
                _errors.Add($"{_context}: expected a {_expectedBase.Name} type name.");
                return null;
            }

            Type _type = ResolveType(_tokens[0], _expectedBase);

            if (_type == null)
            {
                _errors.Add($"{_context}: '{_tokens[0]}' is not a known {_expectedBase.Name} type.");
                return null;
            }

            object _instance = Activator.CreateInstance(_type);
            List<FieldInfo> _fields = SerializedFieldsOf(_type);

            for (int _i = 1; _i < _tokens.Count; _i++)
            {
                int _equals = _tokens[_i].IndexOf('=');

                if (_equals <= 0)
                {
                    _errors.Add($"{_context}: '{_tokens[_i]}' is not a key=value pair.");
                    continue;
                }

                string _key = _tokens[_i].Substring(0, _equals);
                string _value = _tokens[_i].Substring(_equals + 1);

                FieldInfo _field = _fields.Find(_candidate => TrimFieldName(_candidate.Name) == _key);

                if (_field == null)
                {
                    _errors.Add($"{_context}: {_type.Name} has no field '{_key}'. Known fields: {string.Join(", ", _fields.ConvertAll(_f => TrimFieldName(_f.Name)))}.");
                    continue;
                }

                object _parsed = ParseValue(_value, _field.FieldType, $"{_context} {_type.Name}.{_key}", _errors);

                if (_parsed != null || !_field.FieldType.IsValueType)
                    _field.SetValue(_instance, _parsed);
            }

            return _instance;
        }

        private static object ParseValue(string _text, Type _type, string _context, List<string> _errors)
        {
            try
            {
                if (_text == NullToken)
                    return _type.IsValueType ? Activator.CreateInstance(_type) : null;

                if (_type == typeof(bool))
                {
                    switch (_text.ToLowerInvariant())
                    {
                        case "yes":
                        case "true":
                            return true;

                        case "no":
                        case "false":
                            return false;

                        default:
                            _errors.Add($"{_context}: '{_text}' is not yes/no.");
                            return null;
                    }
                }

                if (_type == typeof(string))
                    return Unquote(_text);

                if (_type == typeof(Vector2Int))
                {
                    string[] _parts = _text.Trim('(', ')').Split(',');

                    if (_parts.Length != 2)
                    {
                        _errors.Add($"{_context}: '{_text}' is not a (x,y) pair.");
                        return null;
                    }

                    return new Vector2Int(int.Parse(_parts[0], Invariant), int.Parse(_parts[1], Invariant));
                }

                if (_type.IsEnum)
                    return ParseEnum(_text, _type, _context, _errors);

                if (typeof(UnityEngine.Object).IsAssignableFrom(_type))
                    return ResolveAsset(Unquote(_text), _type, _context, _errors);

                return Convert.ChangeType(_text, _type, Invariant);
            }
            catch (Exception _exception)
            {
                _errors.Add($"{_context}: cannot read '{_text}' as {_type.Name} ({_exception.Message}).");
                return null;
            }
        }

        private static object ParseEnum(string _text, Type _type, string _context, List<string> _errors)
        {
            long _result = 0;

            foreach (string _part in _text.Split('|'))
            {
                string _name = _part.Trim();

                if (long.TryParse(_name, NumberStyles.Integer, Invariant, out long _numeric))
                {
                    _result |= _numeric;
                    continue;
                }

                if (!Enum.IsDefined(_type, _name))
                {
                    _errors.Add($"{_context}: '{_name}' is not a {_type.Name} value. Valid: {string.Join(", ", Enum.GetNames(_type))}.");
                    return null;
                }

                _result |= Convert.ToInt64(Enum.Parse(_type, _name));
            }

            return Enum.ToObject(_type, _result);
        }

        private static UnityEngine.Object ResolveAsset(string _name, Type _type, string _context, List<string> _errors)
        {
            bool _isComponent = typeof(Component).IsAssignableFrom(_type);
            string _filter = _isComponent ? "t:GameObject" : "t:" + _type.Name;

            List<UnityEngine.Object> _matches = new List<UnityEngine.Object>();

            foreach (string _guid in AssetDatabase.FindAssets($"{_name} {_filter}"))
            {
                string _path = AssetDatabase.GUIDToAssetPath(_guid);

                if (Path.GetFileNameWithoutExtension(_path) != _name)
                    continue;

                if (_isComponent)
                {
                    GameObject _prefab = AssetDatabase.LoadAssetAtPath<GameObject>(_path);
                    Component _component = _prefab != null ? _prefab.GetComponent(_type) : null;

                    if (_component != null)
                        _matches.Add(_component);
                }
                else
                {
                    UnityEngine.Object _asset = AssetDatabase.LoadAssetAtPath(_path, _type);

                    if (_asset != null)
                        _matches.Add(_asset);
                }
            }

            if (_matches.Count == 1)
                return _matches[0];

            if (_matches.Count == 0)
                _errors.Add($"{_context}: no {_type.Name} asset named '{_name}'.");
            else
                _errors.Add($"{_context}: {_matches.Count} assets named '{_name}' could be the {_type.Name}; rename one so the reference is unambiguous.");

            return null;
        }

        private static string FormatValue(object _value)
        {
            switch (_value)
            {
                case null:
                    return NullToken;

                case bool _boolean:
                    return _boolean ? "yes" : "no";

                case string _text:
                    return _text.Length == 0 ? NullToken : Quote(_text);

                case Vector2Int _vector:
                    return $"({_vector.x},{_vector.y})";

                case Enum _enumValue:
                    return FormatEnum(_enumValue);

                case float _float:
                    return _float.ToString("R", Invariant);

                case double _double:
                    return _double.ToString("R", Invariant);

                case UnityEngine.Object _unityObject:
                    return Quote(_unityObject.name);

                case IEnumerable _sequence:
                    List<string> _items = new List<string>();

                    foreach (object _item in _sequence)
                        _items.Add(FormatValue(_item));

                    return "[" + string.Join(",", _items) + "]";

                default:
                    return Convert.ToString(_value, Invariant);
            }
        }

        private static string FormatEnum(Enum _value)
        {
            Type _type = _value.GetType();
            string _exactName = Enum.GetName(_type, _value);

            if (_exactName != null)
                return _exactName;

            long _remaining = Convert.ToInt64(_value);
            List<string> _parts = new List<string>();

            foreach (object _candidate in Enum.GetValues(_type))
            {
                long _bit = Convert.ToInt64(_candidate);

                if (_bit == 0 || (_remaining & _bit) != _bit)
                    continue;

                _parts.Add(Enum.GetName(_type, _candidate));
                _remaining &= ~_bit;
            }

            if (_parts.Count == 0 || _remaining != 0)
                return Convert.ToInt64(_value).ToString(Invariant);

            return string.Join("|", _parts);
        }

        private static List<string> Tokenize(string _text)
        {
            List<string> _tokens = new List<string>();
            StringBuilder _current = new StringBuilder();

            bool _inQuotes = false;

            for (int _i = 0; _i < _text.Length; _i++)
            {
                char _character = _text[_i];

                if (_character == '"')
                {
                    _inQuotes = !_inQuotes;
                    _current.Append(_character);
                    continue;
                }

                if (!_inQuotes && char.IsWhiteSpace(_character))
                {
                    if (_current.Length > 0)
                    {
                        _tokens.Add(_current.ToString());
                        _current.Clear();
                    }

                    continue;
                }

                _current.Append(_character);
            }

            if (_current.Length > 0)
                _tokens.Add(_current.ToString());

            return _tokens;
        }

        private static string Quote(string _text)
        {
            bool _needsQuotes = _text.Length == 0 || _text == NullToken;

            foreach (char _character in _text)
                _needsQuotes |= char.IsWhiteSpace(_character) || _character == '"' || _character == '=' || _character == '|';

            if (!_needsQuotes)
                return _text;

            return "\"" + _text.Replace("\"", "\\\"") + "\"";
        }

        private static string Unquote(string _text)
        {
            if (_text.Length >= 2 && _text[0] == '"' && _text[_text.Length - 1] == '"')
                return _text.Substring(1, _text.Length - 2).Replace("\\\"", "\"");

            return _text;
        }

        private static void SplitFirstWord(string _line, out string _word, out string _rest)
        {
            int _space = _line.IndexOf(' ');

            if (_space < 0)
            {
                _word = _line;
                _rest = string.Empty;
                return;
            }

            _word = _line.Substring(0, _space);
            _rest = _line.Substring(_space + 1).Trim();
        }

        private static Type ResolveType(string _name, Type _expectedBase)
        {
            foreach (Type _type in _expectedBase.Assembly.GetTypes())
            {
                if (_type.Name == _name && !_type.IsAbstract && _expectedBase.IsAssignableFrom(_type))
                    return _type;
            }

            return null;
        }

        private static List<FieldInfo> SerializedFieldsOf(Type _type)
        {
            List<Type> _chain = new List<Type>();

            for (Type _current = _type; _current != null && _current != typeof(object); _current = _current.BaseType)
                _chain.Add(_current);

            _chain.Reverse();

            List<FieldInfo> _fields = new List<FieldInfo>();

            foreach (Type _current in _chain)
            {
                foreach (FieldInfo _field in _current.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly))
                {
                    if (_field.IsNotSerialized)
                        continue;

                    bool _isSerialized = _field.IsPublic
                                         || _field.GetCustomAttribute<SerializeField>() != null
                                         || _field.GetCustomAttribute<SerializeReference>() != null;

                    if (_isSerialized)
                        _fields.Add(_field);
                }
            }

            return _fields;
        }

        private static string TrimFieldName(string _name)
        {
            if (_name.StartsWith("m_"))
                return _name.Substring(2);

            return _name.TrimStart('_');
        }

        private static string IdOf(CardConfig _card)
        {
            return string.IsNullOrEmpty(_card.Id) ? _card.name : _card.Id;
        }

        private static string AbsolutePath()
        {
            string _fullPath = Path.Combine(Path.GetDirectoryName(Application.dataPath) ?? ".", FilePath);
            Directory.CreateDirectory(Path.GetDirectoryName(_fullPath) ?? ".");

            return _fullPath;
        }

        private static List<CardConfig> LoadAllCards()
        {
            List<CardConfig> _cards = new List<CardConfig>();

            foreach (string _guid in AssetDatabase.FindAssets("t:CardConfig"))
            {
                CardConfig _card = AssetDatabase.LoadAssetAtPath<CardConfig>(AssetDatabase.GUIDToAssetPath(_guid));

                if (_card != null)
                    _cards.Add(_card);
            }

            _cards.Sort((_a, _b) => string.CompareOrdinal(_a.name, _b.name));

            return _cards;
        }
    }
